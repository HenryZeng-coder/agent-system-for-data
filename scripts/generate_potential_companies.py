def write_csv(filepath: str, header: list[str], rows: list[tuple]):
    with open(filepath, "w", newline="", encoding="utf-8-sig") as f:
        writer = csv.writer(f)
        writer.writerow(header)
        for i, row in enumerate(rows, 1):
            writer.writerow([i, *row])


def main():
    os.makedirs(OUTPUT_DIR, exist_ok=True)

    HEADER = ["id", "company_name", "industry_tags", "business_scope", "registered_capital", "established_year"]

    categories = [
        ("1_software_it_services.csv",   "软件开发与信息技术服务", SOFTWARE_IT),
        ("2_ai_bigdata.csv",             "人工智能与大数据",       AI_BIGDATA),
        ("3_comm_network.csv",           "通信与网络技术",         COMM_NETWORK),
        ("4_electronics_ic.csv",         "电子信息与集成电路",     ELECTRONICS_IC),
        ("5_smart_manufacturing.csv",    "智能制造与工业互联网",   SMART_MANUFACTURING),
    ]

    total = 0
    seen = set()  # 跨文件去重, 首次出现保留
    for filename, category, companies in categories:
        filepath = os.path.join(OUTPUT_DIR, filename)
        deduped = []
        for c in companies:
            if c[0] in seen:
                continue
            seen.add(c[0])
            deduped.append(c)
            if len(deduped) >= 100:  # 每文件恰好 100 家
                break
        write_csv(filepath, HEADER, deduped)
        count = len(deduped)
        total += count
        print(f"✅ {filename}  —  {category}  ({count} 家)")

    print(f"\n总计: {total} 家企业, 输出目录: {OUTPUT_DIR}")
    print(f"去重后唯一企业数: {len(seen)}")


if __name__ == "__main__":
    main()
